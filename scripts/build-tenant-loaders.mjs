#!/usr/bin/env node
/**
 * Generates one loader script per tenant from tenants/<tenantId>.json.
 *
 * A tenant site embeds a single line that never changes:
 *
 *   <script async src="https://cdn.dev.decentcare.ai/t/gowd-dental.js"></script>
 *
 * The loader sets window.OmnilensConfig and then pulls the pinned, immutable
 * tracker build. That means tenant configuration and tracker version are both
 * controlled from this repo — changing either reaches the tenant on the next
 * publish, with no deploy on their side.
 */

import { readdirSync, readFileSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TENANT_DIR = join(ROOT, "tenants");
const OUT_DIR = join(ROOT, ".tenant-build");

// Where tenants fetch the tracker itself from. Baked into each loader, so it can
// be changed centrally without touching a single tenant site.
const CDN_ORIGIN = process.env.OMNILENS_CDN_ORIGIN || "https://cdn.dev.decentcare.ai";

/** Deep merge, with objects merged recursively and scalars overwritten. */
function merge(base, override) {
  const out = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const isPlainObject = (v) => v && typeof v === "object" && !Array.isArray(v);
    out[key] = isPlainObject(value) && isPlainObject(base[key]) ? merge(base[key], value) : value;
  }
  return out;
}

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Turn a merged tenant definition into the config object the tracker reads.
 *
 * `slug` is the public filename only. The tenant the backend attributes data to
 * is `defn.tenantId`, and it is optional:
 *
 *   * set   — sent as x-tenant-id, so attribution does not depend on which
 *             hostname the page is served from.
 *   * unset — the header is omitted and the backend resolves the tenant from the
 *             page hostname via its tenant-hostnames registry.
 *
 * Never fall back to the slug. The backend accepts any string as x-tenant-id and
 * silently returns empty results for one it does not know, so a slug sent as a
 * tenant id produces tracking that looks fine and attributes to nothing.
 */
function buildRuntimeConfig(slug, defn) {
  const apiOrigin = String(defn.apiOrigin || "").replace(/\/$/, "");
  if (!apiOrigin) {
    throw new Error(`${slug}: apiOrigin is required`);
  }

  const tenantId = defn.tenantId ? String(defn.tenantId).trim() : "";
  if (tenantId && !UUID_RE.test(tenantId)) {
    throw new Error(
      `${slug}: tenantId "${tenantId}" is not a UUID. Backend tenant ids are ` +
        `UUIDs; a readable slug here would attribute to a tenant that does not ` +
        `exist. Omit tenantId to resolve by domain instead.`
    );
  }

  // Paths are config, not convention — moving ingest to a different host or URL
  // shape stays a change to tenants/_defaults.json rather than a code change here.
  const paths = defn.apiPaths || {};
  for (const key of ["collect", "assign", "heartbeat"]) {
    if (!paths[key]) throw new Error(`${tenantId}: apiPaths.${key} is required`);
  }

  const { trackerVersion, apiOrigin: _o, apiPaths: _p, ...rest } = defn;

  // Loaders are public files on client websites. Any key starting with "_" is a
  // note to ourselves and must not ship — strip them at every level rather than
  // naming them individually, so a new note can never leak by being forgotten.
  const stripInternal = (value) => {
    if (Array.isArray(value)) return value.map(stripInternal);
    if (value && typeof value === "object") {
      return Object.fromEntries(
        Object.entries(value)
          .filter(([key]) => !key.startsWith("_"))
          .map(([key, v]) => [key, stripInternal(v)])
      );
    }
    return value;
  };

  const clean = stripInternal(rest);
  delete clean.tenantId;

  return {
    ...clean,
    // Only emit tenantId when we actually have one. An empty value would make the
    // tracker skip sendBeacon for no benefit, since it falls back to fetch
    // whenever a tenant header is required.
    ...(tenantId ? { tenantId } : {}),
    collectUrl: `${apiOrigin}${paths.collect}`,
    virtualNumbers: {
      ...clean.virtualNumbers,
      assignUrl: `${apiOrigin}${paths.assign}`,
      heartbeatUrl: `${apiOrigin}${paths.heartbeat}`,
    },
  };
}

function renderLoader(slug, config, trackerVersion) {
  const trackerUrl = `${CDN_ORIGIN}/tracker/v${trackerVersion}/omnilens-tracker.js`;
  const attribution = config.tenantId ? "explicit tenant id" : "resolved by domain";
  // Guard against double-embedding: a tenant with the snippet in both a layout
  // and a tag manager would otherwise run two trackers and double-count.
  return `/* Omnilens loader — ${slug}, tracker v${trackerVersion}, ${attribution}
   Generated by scripts/build-tenant-loaders.mjs. Do not edit by hand. */
(function () {
  if (window.__omnilensLoaded) return;
  window.__omnilensLoaded = true;

  window.OmnilensConfig = ${JSON.stringify(config, null, 2)};

  var s = document.createElement('script');
  s.src = ${JSON.stringify(trackerUrl)};
  s.async = true;
  document.head.appendChild(s);
})();
`;
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(join(OUT_DIR, "t"), { recursive: true });

const defaults = readJson(join(TENANT_DIR, "_defaults.json"));
const tenantFiles = readdirSync(TENANT_DIR)
  .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
  .sort();

if (tenantFiles.length === 0) {
  console.error("No tenant definitions found in tenants/");
  process.exit(1);
}

for (const file of tenantFiles) {
  // Filename is the public slug. It is NOT the tenant id — see buildRuntimeConfig.
  const slug = file.replace(/\.json$/, "");
  const defn = merge(defaults, readJson(join(TENANT_DIR, file)));
  const config = buildRuntimeConfig(slug, defn);
  const loader = renderLoader(slug, config, defn.trackerVersion);

  writeFileSync(join(OUT_DIR, "t", `${slug}.js`), loader);
  console.log(
    `${slug.padEnd(16)} v${defn.trackerVersion}  ` +
      `vn=${config.virtualNumbers.enabled ? "on " : "off"}  ` +
      `wa=${config.whatsapp.enabled ? "on " : "off"}  ` +
      `tenant=${config.tenantId || "(by domain)"}`
  );
}

console.log(`\n${tenantFiles.length} loader(s) written to .tenant-build/t/`);
